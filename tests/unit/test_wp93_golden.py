def test_same_surface(results: tuple[dict[str, Any], dict[str, Any]]) -> None:
    baseline, current = results
    assert sorted(current) == sorted(baseline)


@pytest.mark.parametrize(
    "key",
    sorted(k for k in json.loads(_BASELINE.read_text(encoding="utf-8")) if k != "_meta" and k not in _D070_RETIRED_KEYS),
)
def test_matches_v2_baseline(key: str, results: tuple[dict[str, Any], dict[str, Any]]) -> None:
    baseline, current = results
    if key == "presets:keyword_fallback":
        # Removing the privileged-default deferral changes only this one row's
        # position. Preserve every preset/area pair and all other row ordering.
        assert current[key] == [baseline[key][-1], *baseline[key][:-1]]
        return
    if key == "presets:keyword_suggest":
        assert len(current[key]) == len(baseline[key])
        for index, (actual, historical) in enumerate(zip(current[key], baseline[key], strict=True)):
            if index in _D070_NO_MATCH_INDICES:
                expected = {"preset_id": "", "primary_area": "andere", "secondary_areas": [],
                            "match": "keyword_fallback", "suggestions": []}
            elif index in _D070_TIE_CANDIDATE_INDICES:
                expected = {"preset_id": "", "primary_area": "andere", "secondary_areas": [],
                            "match": "keyword_fallback", "suggestions": [
                                {field: value for field, value in baseline[key][candidate].items()
                                 if field != "match"}
                                for candidate in _D070_TIE_CANDIDATE_INDICES[index]
                            ]}
            else:
                expected = {**historical, "suggestions": [
                    {field: value for field, value in historical.items() if field != "match"}
                ]}
            assert actual == expected, index
        return
    # JSON round-trip normalises tuples/lists exactly as the baseline file did.
    assert json.loads(json.dumps(current[key], default=str)) == baseline[key], key
