"""WP-93 zero-behaviour-change golden (roadmap WP-93/WP-97, refactor invariant).

Everything WP-93 moved from the core into module data/code — stage prompts,
intake/preset tables and prompts, corpus source mapping and BGB § tagging,
regime banners, calculation prompts, document selection and 3,600 rendered
draft variants — must produce exactly what the v2.0.0 core produced.
``golden/wp93_v2_baseline.json`` was generated by running
``wp93_golden_collect.collect`` against the pre-WP-93 tree (commit aae2888).

A deliberate behaviour change to any of these surfaces must regenerate the
baseline in the same change and be recorded in DECISIONS.md.
"""

# Semantic Version: 1.0.0

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from citizen_modules.sozialrecht.calculators import SGB2_CALCULATOR
from citizen_modules.sozialrecht.regime import legal_regime, regime_banner
from citizen_modules.sozialrecht.rules_engine import ReconciliationLineItem
from tests.unit.sozialrecht_fristen import compute_widerspruchsfrist
from tests.unit.wp93_golden_collect import collect

_BASELINE = Path(__file__).with_name("golden") / "wp93_v2_baseline.json"


@pytest.fixture(scope="module")
def results() -> tuple[dict[str, Any], dict[str, Any]]:
    from app.api.routes import presets as presets_route
    from app.services import corpus, intake
    from app.services.corpus_readiness import AREA_TO_SOURCE_TYPES
    from app.services.document_generators import generate_document, select_generator
    from app.services.presets import list_presets
    from app.services.prompts import get_prompts

    adapter = {
        "get_prompts": get_prompts,
        "intake": intake,
        "presets_route": presets_route,
        "list_presets": list_presets,
        "area_source_types": lambda: AREA_TO_SOURCE_TYPES,
        "infer_bgb_area": corpus._infer_legal_area_for_bgb,
        "legal_regime": legal_regime,
        "regime_banner": regime_banner,
        "compute_frist": compute_widerspruchsfrist,
        "line_item_cls": ReconciliationLineItem,
        "generate_document": generate_document,
        "select_generator": select_generator,
        "extraction_prompt": SGB2_CALCULATOR.extraction_prompt,
        "explanation_prompt": SGB2_CALCULATOR.explanation_prompt,
        "referral_hint": SGB2_CALCULATOR.referral_hint,
    }
    baseline = json.loads(_BASELINE.read_text(encoding="utf-8"))
    baseline.pop("_meta")
    return baseline, collect(adapter)


def test_same_surface(results: tuple[dict[str, Any], dict[str, Any]]) -> None:
    baseline, current = results
    assert sorted(current) == sorted(baseline)


@pytest.mark.parametrize(
    "key",
    sorted(k for k in json.loads(_BASELINE.read_text(encoding="utf-8")) if k != "_meta"),
)
def test_matches_v2_baseline(key: str, results: tuple[dict[str, Any], dict[str, Any]]) -> None:
    baseline, current = results
    # JSON round-trip normalises tuples/lists exactly as the baseline file did.
    assert json.loads(json.dumps(current[key], default=str)) == baseline[key], key
